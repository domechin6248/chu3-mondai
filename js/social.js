  function genScale() {
    const scale = pick([25000, 50000]);
    const label = scale === 25000 ? '2万5千分の1' : '5万分の1';
    const cm = rand(1, 40) / 2;
    const meters = round(cm * scale / 100);
    if (Math.random() < 0.5) {
      return make({
        category: '地理（地形図）',
        question: `${label}の地形図上で ${dec(cm)}cm の長さは、実際には何mか。`,
        answer: `${meters} m`,
        distractors: [`${meters * 2} m`, `${dec(meters / 2)} m`, `${meters * 10} m`, `${dec(meters / 10)} m`],
        explanation: `実際の距離 = 地図上の長さ × 縮尺の分母\n${dec(cm)}cm × ${scale} = ${dec(cm * scale)}cm = ${meters}m`,
      });
    }
    return make({
      category: '地理（地形図）',
      question: `実際の距離が ${meters}m のとき、${label}の地形図上では何cmになるか。`,
      answer: `${dec(cm)} cm`,
      distractors: [`${dec(cm * 2)} cm`, `${dec(cm / 2)} cm`, `${dec(cm * 10)} cm`, `${dec(cm / 10)} cm`],
      explanation: `地図上の長さ = 実際の距離 ÷ 縮尺の分母\n${meters}m = ${meters * 100}cm、${meters * 100} ÷ ${scale} = ${dec(cm)}cm`,
    });
  }

